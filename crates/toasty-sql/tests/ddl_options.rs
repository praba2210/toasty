use toasty_core::{
    driver::Capability,
    schema::{
        db::{
            Column, ColumnId, Index, IndexColumn, IndexId, IndexOp, IndexScope, PrimaryKey, Schema,
            Table, TableId, Type,
        },
        diff,
    },
    stmt as core_stmt,
};
use toasty_sql::{Serializer, migration::MigrationStatement, stmt::DdlOptions};

const DSQL_OPTIONS: DdlOptions = DdlOptions {
    async_index: true,
    identity_cache: Some(65_536),
};

fn make_column(index: usize, name: &str, auto_increment: bool) -> Column {
    Column {
        id: ColumnId {
            table: TableId(0),
            index,
        },
        name: name.to_string(),
        ty: core_stmt::Type::I64,
        storage_ty: Type::Integer(8),
        nullable: false,
        primary_key: index == 0,
        auto_increment,
        versionable: false,
    }
}

fn make_table(columns: Vec<Column>, indices: Vec<Index>) -> Table {
    Table {
        id: TableId(0),
        name: "users".to_string(),
        columns,
        primary_key: PrimaryKey {
            columns: vec![ColumnId {
                table: TableId(0),
                index: 0,
            }],
            index: IndexId {
                table: TableId(0),
                index: 0,
            },
        },
        indices,
    }
}

fn unique_index() -> Index {
    Index {
        id: IndexId {
            table: TableId(0),
            index: 0,
        },
        name: "idx_users_code".to_string(),
        on: TableId(0),
        columns: vec![IndexColumn {
            column: ColumnId {
                table: TableId(0),
                index: 1,
            },
            op: IndexOp::Eq,
            scope: IndexScope::Local,
        }],
        unique: true,
        primary_key: false,
    }
}

fn migration_sql(from: &Schema, to: &Schema, options: &DdlOptions) -> Vec<String> {
    let hints = diff::RenameHints::new();
    let diff = diff::Schema::from(from, to, &hints);
    MigrationStatement::from_diff_with(&diff, &Capability::POSTGRESQL, options)
        .iter()
        .map(|ms| Serializer::postgresql(ms.schema()).serialize(ms.statement()))
        .collect()
}

fn users_schema() -> Schema {
    Schema {
        tables: vec![make_table(
            vec![make_column(0, "id", true), make_column(1, "code", false)],
            vec![unique_index()],
        )],
    }
}

#[test]
fn default_options_render_plain_ddl() {
    let sql = migration_sql(&Schema::default(), &users_schema(), &DdlOptions::default());

    assert_eq!(
        sql,
        [
            "CREATE TABLE \"users\" (\n    \"id\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,\n    \"code\" BIGINT NOT NULL,\n    PRIMARY KEY (\"id\")\n);",
            "CREATE UNIQUE INDEX \"idx_users_code\" ON \"users\" (\"code\");",
        ]
    );
}

#[test]
fn options_render_async_index_and_identity_cache() {
    let sql = migration_sql(&Schema::default(), &users_schema(), &DSQL_OPTIONS);

    assert_eq!(
        sql,
        [
            "CREATE TABLE \"users\" (\n    \"id\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (CACHE 65536),\n    \"code\" BIGINT NOT NULL,\n    PRIMARY KEY (\"id\")\n);",
            "CREATE UNIQUE INDEX ASYNC \"idx_users_code\" ON \"users\" (\"code\");",
        ]
    );
}

#[test]
fn options_render_identity_cache_on_added_and_altered_columns() {
    let from = Schema {
        tables: vec![make_table(
            vec![make_column(0, "id", false), make_column(1, "code", false)],
            vec![],
        )],
    };
    let to = Schema {
        tables: vec![make_table(
            vec![
                make_column(0, "id", true),
                make_column(1, "code", false),
                make_column(2, "seq", true),
            ],
            vec![],
        )],
    };

    let mut sql = migration_sql(&from, &to, &DSQL_OPTIONS);
    sql.sort();

    assert_eq!(
        sql,
        [
            "ALTER TABLE \"users\" ADD COLUMN \"seq\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (CACHE 65536);",
            "ALTER TABLE \"users\" ALTER COLUMN \"id\" ADD GENERATED BY DEFAULT AS IDENTITY (CACHE 65536);",
        ]
    );
}
